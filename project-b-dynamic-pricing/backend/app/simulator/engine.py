"""Vectorised simulator with common random numbers (CRN).

Exogenous information W_{t+1} on day t for scenario s is a pair of uniforms
(U^arr_{s,t}, U^buy_{s,t}); each scenario also has one uniform U^lvl_s that
fixes its (unobserved) demand level M_s = exp(σ_D Φ^{-1}(U^lvl) − σ_D²/2).
They are turned into outcomes by inversion:

    N_t = F^{-1}_{Poisson(M·λ_t·m_t)}(U^arr)     potential buyers that arrive
          (m_t = κ when fewer than 10% of seats remain, else 1)
    B_t = F^{-1}_{Binomial(N_t, q(p_t, r_t))}(U^buy)   of those, how many have WTP ≥ p̃_t
    sales_t = min(B_t, R_t)

Because each arriving buyer independently clears the threshold with
probability q (lognormal WTP), B_t has exactly the distribution implied by
drawing N_t individual WTPs and applying the purchase rule — but every policy
sees the SAME uniforms, so outcomes are monotonically coupled across policies
(a policy that charges less on a given day never sells fewer tickets than one
charging more, all else equal).  That is what makes paired comparisons tight.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Protocol

import numpy as np
from scipy.special import ndtri
from scipy.stats import binom, poisson

from .demand import purchase_prob, update_reference
from .params import MarketParams

_EPS = 1e-12


@dataclass
class Scenarios:
    family: int
    ids: np.ndarray            # (S,)
    u_arr: np.ndarray          # (S, T)
    u_buy: np.ndarray          # (S, T)
    u_level: np.ndarray        # (S,)

    def level(self, demand_sigma: float) -> np.ndarray:
        """M_s, the scenario's demand multiplier (mean 1)."""
        if demand_sigma <= 0:
            return np.ones(self.n)
        return np.exp(demand_sigma * ndtri(self.u_level) - 0.5 * demand_sigma ** 2)

    @property
    def n(self) -> int:
        return int(self.ids.shape[0])

    def subset(self, idx: np.ndarray) -> "Scenarios":
        return Scenarios(self.family, self.ids[idx], self.u_arr[idx], self.u_buy[idx], self.u_level[idx])


def make_scenarios(family: int, n: int, horizon: int, start: int = 0) -> Scenarios:
    """Scenario s is generated by default_rng([family, s]) — reproducible and
    independent of how many other scenarios are requested."""
    ids = np.arange(start, start + n)
    u_arr = np.empty((n, horizon))
    u_buy = np.empty((n, horizon))
    u_level = np.empty(n)
    for k, sid in enumerate(ids):
        rng = np.random.default_rng([family, int(sid)])
        u_level[k] = rng.random()
        u = rng.random((2, horizon))
        u_arr[k], u_buy[k] = u[0], u[1]
    for a in (u_arr, u_buy, u_level):
        np.clip(a, _EPS, 1 - _EPS, out=a)
    return Scenarios(family, ids, u_arr, u_buy, u_level)


@dataclass
class State:
    """Pre-decision state S_t, batched over scenarios."""
    t: int                     # day index (0-based)
    days_left: int             # d_t = T - t
    seats: np.ndarray          # R_t, seats remaining (int)
    ref: np.ndarray            # r_t, reference price ($)
    last_sales: np.ndarray     # s_{t-1}, tickets sold yesterday
    sold: np.ndarray           # C - R_t (convenience)
    exp_sold: np.ndarray       # Σ_{τ<t} E[sales_τ | M=1, posted prices] — with `sold`, a sufficient
                               # statistic for the belief about the unknown demand level M
    scenario_ids: np.ndarray = field(repr=False, default_factory=lambda: np.empty(0))


class Policy(Protocol):
    name: str

    def reset(self, params: MarketParams, n: int) -> None: ...

    def act(self, state: State, params: MarketParams) -> np.ndarray:
        """Return grid indices (int array, shape (S,))."""
        ...


@dataclass
class SimResult:
    revenue: np.ndarray        # (S,)  total revenue $
    sold: np.ndarray           # (S,)  tickets sold
    sellout: np.ndarray        # (S,)  bool, all seats sold before the event
    sellout_day: np.ndarray    # (S,)  days left when the last seat sold (0 if never)
    prices: np.ndarray         # (S, T) posted price
    sales: np.ndarray          # (S, T)
    arrivals: np.ndarray       # (S, T)
    ref: np.ndarray            # (S, T) reference price at the start of day t
    seats: np.ndarray          # (S, T) seats at the start of day t
    level: np.ndarray          # (S,)  realised demand level M (hidden from policies)


def scarcity_multiplier(params: MarketParams, seats: np.ndarray) -> np.ndarray:
    return np.where(seats < params.scarcity_frac * params.capacity, params.kappa, 1.0)


def step_outcome(params: MarketParams, t: int, price: np.ndarray, ref: np.ndarray,
                 seats: np.ndarray, u_arr: np.ndarray, u_buy: np.ndarray,
                 lam: np.ndarray | None = None, level: np.ndarray | float = 1.0) -> tuple[np.ndarray, np.ndarray]:
    """Arrivals and sales for one day (transition kernel, vectorised)."""
    if lam is None:
        lam = params.arrival_rates()
    rate = level * lam[t] * scarcity_multiplier(params, seats)
    n_arr = poisson.ppf(u_arr, rate).astype(np.int64)
    q = purchase_prob(price, ref, params.eta, params.gamma, params.wtp_mu, params.wtp_sigma)
    q = np.clip(q, 0.0, 1.0)
    willing = binom.ppf(u_buy, n_arr, q)
    willing = np.nan_to_num(willing, nan=0.0).astype(np.int64)
    sales = np.minimum(willing, seats)
    return n_arr, sales


def simulate(policy: Policy, params: MarketParams, sc: Scenarios) -> SimResult:
    T, S = params.horizon, sc.n
    grid = params.grid
    lam = params.arrival_rates()
    seats = np.full(S, params.capacity, dtype=np.int64)
    ref = np.full(S, params.ref_init, dtype=float)
    last = np.zeros(S, dtype=np.int64)
    exp_sold = np.zeros(S)
    level = sc.level(params.demand_sigma)
    out_p = np.empty((S, T)); out_s = np.zeros((S, T), dtype=np.int64)
    out_a = np.zeros((S, T), dtype=np.int64); out_r = np.empty((S, T)); out_R = np.empty((S, T), dtype=np.int64)
    revenue = np.zeros(S)
    sellout_day = np.zeros(S, dtype=np.int64)
    policy.reset(params, S)
    for t in range(T):
        state = State(t=t, days_left=T - t, seats=seats.copy(), ref=ref.copy(), last_sales=last.copy(),
                      sold=params.capacity - seats, exp_sold=exp_sold.copy(), scenario_ids=sc.ids)
        idx = np.asarray(policy.act(state, params), dtype=np.int64)
        idx = np.clip(idx, 0, len(grid) - 1)
        price = grid[idx]
        n_arr, sales = step_outcome(params, t, price, ref, seats, sc.u_arr[:, t], sc.u_buy[:, t], lam, level)
        q = purchase_prob(price, ref, params.eta, params.gamma, params.wtp_mu, params.wtp_sigma)
        exp_sold += np.where(seats > 0, lam[t] * scarcity_multiplier(params, seats) * q, 0.0)
        out_p[:, t], out_r[:, t], out_R[:, t] = price, ref, seats
        out_a[:, t], out_s[:, t] = n_arr, sales
        revenue += price * sales
        new_seats = seats - sales
        just_out = (seats > 0) & (new_seats == 0)
        sellout_day[just_out] = T - t
        seats = new_seats
        last = sales
        ref = update_reference(ref, price, params.theta)
    sold = params.capacity - seats
    return SimResult(revenue=revenue, sold=sold, sellout=seats == 0, sellout_day=sellout_day,
                     prices=out_p, sales=out_s, arrivals=out_a, ref=out_r, seats=out_R, level=level)
