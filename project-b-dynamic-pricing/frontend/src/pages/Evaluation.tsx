import { useData } from "../lib/data";
import { useLang } from "../lib/i18n";
import { kMoney, money, num, pct } from "../lib/format";
import { ErrorBox, Loading, Panel, PolicyName } from "../components/ui";
import { ResultsTable } from "../components/Results";
import { RevenueHistogram } from "../components/charts";

export function EvaluationPage() {
  const { pre, error, reload } = useData();
  const { p, t, lang } = useLang();
  if (error) return <ErrorBox msg={error} onRetry={reload} />;
  if (!pre) return <Loading />;
  const s = pre.seeds;
  const rec = pre.recommendation;
  return (
    <>
      <h1>{p("A fair fight", "Una pelea justa")}</h1>
      <p className="lede">
        {p("Every policy is run in the same simulator on the same random selling seasons. Tuning and evaluation never share random numbers.",
          "Cada política se corre en el mismo simulador sobre las mismas temporadas de venta aleatorias. El ajuste y la evaluación nunca comparten números aleatorios.")}
      </p>

      <Panel title={p("Protocol", "Protocolo")}>
        <div className="scrollx">
          <table className="t">
            <thead><tr><th>{p("Stage", "Etapa")}</th><th>{p("Seed family", "Familia de semillas")}</th><th>{p("Scenarios", "Escenarios")}</th><th style={{ textAlign: "left" }}>{p("Used for", "Uso")}</th></tr></thead>
            <tbody>
              <tr><td>{p("Tuning", "Ajuste")}</td><td>{s.tuning_family}</td><td>{num(s.n_tune, lang)}</td><td style={{ textAlign: "left", whiteSpace: "normal" }}>{p("best fixed price, rule parameters", "mejor precio fijo, parámetros de la regla")}</td></tr>
              <tr><td>{p("Tuning (DLA)", "Ajuste (DLA)")}</td><td>{s.tuning_family}</td><td>{num(s.n_tune_dla, lang)}</td><td style={{ textAlign: "left", whiteSpace: "normal" }}>{p("lookahead prior strength n₀", "fuerza de la previa n₀ de la anticipación")}</td></tr>
              <tr><td>{p("RL training", "Entrenamiento RL")}</td><td>{s.rl_train_family ?? "—"}</td><td>{pre.rl.train_meta ? num(pre.rl.train_meta.episodes, lang) : "—"}</td><td style={{ textAlign: "left", whiteSpace: "normal" }}>{p("DQN episodes (validation on family 11,500)", "episodios DQN (validación en la familia 11,500)")}</td></tr>
              <tr className="rec"><td><strong>{p("Final evaluation", "Evaluación final")}</strong></td><td>{s.eval_family}</td><td><strong>{num(s.n_eval, lang)}</strong></td><td style={{ textAlign: "left", whiteSpace: "normal" }}>{p("every number in the results tables", "todos los números de las tablas de resultados")}</td></tr>
              <tr><td>{p("Sensitivity", "Sensibilidad")}</td><td>{pre.sensitivity?.seed_family ?? "—"}</td><td>{pre.sensitivity ? num(pre.sensitivity.n_scenarios, lang) : "—"}</td><td style={{ textAlign: "left", whiteSpace: "normal" }}>{p("per point of each sweep", "por punto de cada barrido")}</td></tr>
            </tbody>
          </table>
        </div>
        <p className="small muted" style={{ marginTop: "0.7rem" }}>
          {p("Scenario i of family f is generated by numpy's default_rng([f, i]): one demand-level uniform plus two uniforms per day (arrivals, purchases). Common random numbers make paired differences far tighter than the spread of revenue itself.",
            "El escenario i de la familia f se genera con default_rng([f, i]) de numpy: un uniforme de nivel de demanda más dos uniformes por día (llegadas, compras). Los números aleatorios comunes hacen que las diferencias pareadas sean mucho más estrechas que la dispersión del ingreso.")}
        </p>
      </Panel>

      <Panel title={p("Main metric: total revenue per event", "Métrica principal: ingreso total por evento")}
        sub={p("Mean, 95% confidence interval of the mean (normal approximation), standard deviation and 5th/95th percentiles.", "Media, intervalo de confianza del 95% de la media (aproximación normal), desviación estándar y percentiles 5/95.")}>
        <ResultsTable study={pre} />
      </Panel>

      <Panel title={p("Secondary metrics", "Métricas secundarias")}>
        <div className="scrollx">
          <table className="t">
            <thead><tr><th>{t("m.policy")}</th><th>{t("m.sellout")}</th><th>{p("95% CI (Wilson)", "IC 95% (Wilson)")}</th><th>{t("m.sold")}</th><th>{t("m.unsold")}</th><th>{t("m.avgpaid")}</th><th>{p("Days left at sell-out", "Días restantes al agotar")}</th><th>{t("m.firstprice")}</th></tr></thead>
            <tbody>
              {pre.order.map((k) => {
                const m = pre.policies[k]!.summary;
                return (
                  <tr key={k}>
                    <td><PolicyName k={k} /></td>
                    <td>{pct(m.sellout.prob, lang, 1)}</td>
                    <td>{pct(m.sellout.ci95[0], lang, 1)} – {pct(m.sellout.ci95[1], lang, 1)}</td>
                    <td>{num(m.tickets.mean_sold, lang)}</td>
                    <td>{num(m.tickets.mean_unsold, lang)}</td>
                    <td>{money(m.avg_price_paid, lang, 2)}</td>
                    <td>{m.sellout.mean_days_left_at_sellout === null ? "—" : num(m.sellout.mean_days_left_at_sellout, lang, 1)}</td>
                    <td>{money(m.first_price, lang)}</td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      </Panel>

      <Panel title={p("Paired differences against the fixed price", "Diferencias pareadas contra el precio fijo")}
        sub={p("Same scenario, two policies: revenue(policy) − revenue(fixed).", "Mismo escenario, dos políticas: ingreso(política) − ingreso(fijo).")}>
        <div className="scrollx">
          <table className="t">
            <thead><tr><th>{t("m.policy")}</th><th>{p("Mean difference", "Diferencia media")}</th><th>{p("95% CI", "IC 95%")}</th><th>{p("Std. of difference", "Desv. de la diferencia")}</th><th>{t("m.win")}</th></tr></thead>
            <tbody>
              {pre.order.filter((k) => k !== "fixed").map((k) => {
                const g = pre.policies[k]!.summary.paired_vs_fixed!;
                return (
                  <tr key={k}>
                    <td><PolicyName k={k} /></td>
                    <td>{kMoney(g.mean, lang, 2)}</td>
                    <td>{kMoney(g.ci95[0], lang, 2)} – {kMoney(g.ci95[1], lang, 2)}</td>
                    <td>{kMoney(g.sd, lang, 2)}</td>
                    <td>{pct(g.win_rate, lang, 1)}</td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
        {rec.edge_vs_runner_up && rec.runner_up && (
          <p className="small" style={{ marginTop: "0.7rem" }}>
            {p("Recommended vs. runner-up", "Recomendada vs. segunda")} (<PolicyName k={rec.policy} short /> − <PolicyName k={rec.runner_up} short />):{" "}
            {kMoney(rec.edge_vs_runner_up.mean, lang, 2)} [{kMoney(rec.edge_vs_runner_up.ci95[0], lang, 2)}, {kMoney(rec.edge_vs_runner_up.ci95[1], lang, 2)}],{" "}
            {p("better in", "mejor en")} {pct(rec.edge_vs_runner_up.win_rate, lang)} {p("of scenarios.", "de los escenarios.")}
          </p>
        )}
        <p className="small muted">
          {p("Decision rule: recommend the highest mean, unless a simpler policy (fixed < rule < lookahead < RL) is statistically tied with it, in which case recommend the simpler one. RL is never recommended when out-of-distribution.",
            "Regla de decisión: recomendar la mayor media, salvo que una política más simple (fijo < regla < anticipación < RL) empate estadísticamente con ella; en ese caso se recomienda la más simple. RL nunca se recomienda fuera de distribución.")}
        </p>
      </Panel>

      <Panel title={p("Revenue distribution", "Distribución del ingreso")}>
        <RevenueHistogram study={pre} keys={pre.order} height={300} />
      </Panel>
      {pre.total_seconds !== undefined && (
        <p className="small muted">{p("Full precompute took", "El precálculo completo tardó")} {num(pre.total_seconds / 60, lang, 1)} min.</p>
      )}
    </>
  );
}
